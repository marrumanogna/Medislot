def data_markdown():
    schema = (ROOT / "scehma" / "schema.sql").read_text(encoding="utf-8-sig")
    out = ["# Data model", "", "Generated by `scripts/generate_docs.py`. System of record is **RDS MySQL**; "
           "fast-changing state (seats, offers, tokens, dispatch log) lives in **DynamoDB**.", "",
           "## RDS MySQL (`scehma/schema.sql`)", ""]
    for name, body in re.findall(r"CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\n\) ENGINE", schema, re.S):
        cols = [ln.strip().split()[0] for ln in body.split("\n")
                if ln.strip() and ln.strip().split()[0].isidentifier() and ln.strip().split()[0].upper() not in
                ("PRIMARY", "UNIQUE", "KEY", "CONSTRAINT", "INDEX", "FOREIGN", "CHECK", "FULLTEXT")]
        out += [f"### `{name}`", RDS_PURPOSE.get(name, ""), "", "Columns: " + ", ".join(f"`{c}`" for c in cols), ""]
    out += ["## DynamoDB (`cloudformation/data-stack.yaml`)", "", "| Table | Key | TTL | Purpose |", "|---|---|---|---|"]
    for v in load("data-stack.yaml").values():
        if v["Type"] != "AWS::DynamoDB::Table":
            continue
        p = v["Properties"]
        short = p["TableName"].split("-")[-1]
        key = " + ".join(f"{k['AttributeName']} ({k['KeyType']})" for k in p["KeySchema"])
        ttl = p.get("TimeToLiveSpecification", {}).get("AttributeName", "-")
        out.append(f"| {short} | {key} | {ttl} | {DYNAMO_PURPOSE.get(short, '')} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    (ROOT / "docs" / "api.md").write_text(api_markdown(), encoding="utf-8")
    (ROOT / "docs" / "data-model.md").write_text(data_markdown(), encoding="utf-8")
    print("docs/api.md and docs/data-model.md written")
