"""Regenerate docs/api.md and docs/data-model.md from the CloudFormation templates and schema.

Usage:  python scripts/generate_docs.py        (needs PyYAML)
The files are generated, so edit this script - not the markdown - when the format needs to change.
"""
import pathlib
import re

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]


class Loader(yaml.SafeLoader):
    """CloudFormation short tags (!Ref, !Sub, ...) are read as plain strings."""


def _any_tag(loader, suffix, node):
    if isinstance(node, yaml.ScalarNode):
        return loader.construct_scalar(node)
    if isinstance(node, yaml.SequenceNode):
        return loader.construct_sequence(node, deep=True)
    return loader.construct_mapping(node, deep=True)


Loader.add_multi_constructor("!", _any_tag)


def load(name):
    return yaml.load((ROOT / "cloudformation" / name).read_text(encoding="utf-8-sig"), Loader)["Resources"]


# --------------------------------------------------------------------------- API reference
def api_markdown():
    res = load("auth-stack.yaml")
    segments = {k: (v["Properties"]["ParentId"], v["Properties"]["PathPart"])
                for k, v in res.items() if v["Type"] == "AWS::ApiGateway::Resource"}

    def path_of(key):
        parts = []
        while key in segments:
            key, part = segments[key][0], segments[key][1]
            parts.append(part)
        return "/" + "/".join(reversed(parts))

    rows = []
    for v in res.values():
        if v["Type"] != "AWS::ApiGateway::Method":
            continue
        p = v["Properties"]
        if p["HttpMethod"] == "OPTIONS":
            continue
        found = re.search(r"\$\{(\w+)Function\.Arn\}", str(p.get("Integration", {}).get("Uri", "")))
        rows.append((path_of(p["ResourceId"]), p["HttpMethod"], "JWT" if p.get("AuthorizationType") == "CUSTOM" else "Public",
                     found.group(1) if found else "-"))
    rows.sort()
    out = ["# API reference", "",
           "Generated by `scripts/generate_docs.py` from `cloudformation/auth-stack.yaml`. Base URL: the `ApiUrl` output of the auth stack.",
           "Protected routes need `Authorization: Bearer <access token>`; the role (PATIENT or DOCTOR) is enforced inside each Lambda.", "",
           "| Method | Path | Auth | Lambda |", "|---|---|---|---|"]
    out += [f"| {m} | `{p}` | {a} | {fn} |" for p, m, a, fn in rows]
    out += ["", f"Total: {len(rows)} endpoints.", "",
            "Common error body: `{\"message\": \"...\", \"code\": \"...\", \"correlationId\": \"...\"}`. "
            "Booking and reschedule accept an `Idempotency-Key` header so a retry never double-books."]
    return "\n".join(out) + "\n"


